#!/usr/bin/env python3
"""Generate components/wa/wa_tokens.c from whatsmeow's binary/token/token.go.

Usage: gen_tokens.py path/to/whatsmeow/binary/token/token.go > components/wa/wa_tokens.c

Reads the token tables as data; nothing from the Go file is executed.
"""
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()


def strings(block):
    return re.findall(r'"((?:[^"\\]|\\.)*)"', block)


single = re.search(r"SingleByteTokens = \[\.\.\.\]string\{(.*?)\}\n", src, re.S).group(1)
double = re.search(r"DoubleByteTokens = \[\.\.\.\]\[\]string\{(.*?)\n\t\}\n", src, re.S).group(1)
dict_version = re.search(r"const DictVersion = (\d+)", src).group(1)
single_tokens = strings(single)
double_dicts = [strings(m) for m in re.findall(r"\{(.*?)\}", double, re.S)]
assert len(double_dicts) == 4, len(double_dicts)
assert all(len(d) <= 256 for d in double_dicts)


def c(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


out = [
    "// SPDX-License-Identifier: MPL-2.0",
    "// Generated by tools/gen_tokens.py from whatsmeow binary/token/token.go. Do not edit.",
    '#include "wa_binary.h"',
    "",
    f"const uint8_t WA_DICT_VERSION = {dict_version};",
    f"const size_t WA_SINGLE_TOKEN_COUNT = {len(single_tokens)};",
    "const char *const WA_SINGLE_TOKENS[] = {",
]
out += [f"    {c(t)}," for t in single_tokens]
out += ["};", f"const size_t WA_DOUBLE_TOKEN_COUNT[4] = {{{', '.join(str(len(d)) for d in double_dicts)}}};"]
for i, d in enumerate(double_dicts):
    out.append(f"static const char *const D{i}[] = {{")
    out += [f"    {c(t)}," for t in d]
    out.append("};")
out.append("const char *const *const WA_DOUBLE_TOKENS[4] = {D0, D1, D2, D3};")
print("\n".join(out))
